#!/usr/bin/env node
// Undercurrent 2 · FEATURES — embed the JSON data files as ES modules so the browser and node load them without fetch
// or JSON import attributes. Run after editing extension/data/rulepacks/*.json or extension/data/slop.json:
//     node extension/src/features/sync-data.mjs          (write)
//     node extension/src/features/sync-data.mjs --check  (exit 1 when the modules are stale)
// Node-only; never imported by the extension.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.resolve(HERE, '../../data');

export function buildPacksModule() {
    const dir = path.join(DATA, 'rulepacks');
    const files = fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort();
    const packs = files.map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
    return `// GENERATED by extension/src/features/sync-data.mjs from extension/data/rulepacks/*.json — edit the JSON, then re-run.\n`
        + `export const STARTER_PACKS = ${JSON.stringify(packs, null, 1)};\n`;
}

export function buildSlopModule() {
    const data = JSON.parse(fs.readFileSync(path.join(DATA, 'slop.json'), 'utf8'));
    return `// GENERATED by extension/src/features/sync-data.mjs from extension/data/slop.json — edit the JSON, then re-run.\n`
        + `export const SLOP_DATA = ${JSON.stringify(data, null, 1)};\n`;
}

export const TARGETS = [
    [path.join(HERE, 'chance/packs.js'), buildPacksModule],
    [path.join(HERE, 'ticguard/slop_data.js'), buildSlopModule],
];

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const check = process.argv.includes('--check');
    let stale = 0;
    for (const [file, build] of TARGETS) {
        const text = build();
        const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
        if (cur === text) continue;
        stale++;
        if (check) console.error(`stale: ${path.relative(process.cwd(), file)}`);
        else { fs.writeFileSync(file, text); console.log(`wrote ${path.relative(process.cwd(), file)}`); }
    }
    if (check && stale) process.exit(1);
}
