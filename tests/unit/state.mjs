import assert from 'node:assert/strict';
const chat = [];
let saves = 0;
globalThis.SillyTavern = { getContext: () => ({ chat, saveChat: () => { saves++; } }) };
const { stateAt, statePrompt, editState, changesFromProfiles } = await import('../../src/state.js');
const msg = (record) => ({ extra: { roleplay_instructions: record } });
chat.push(msg({ stateChanges: [{ name: 'Hale', fields: { mind: 'Find the letter', body: 'Sore shoulder' } }], scene: { present: 'Hale' } }));
chat.push({ is_user: true, mes: 'Hello' });
assert.match(statePrompt(), /Sore shoulder/);
assert.match(statePrompt(), /other characters know only/);
assert(editState(0, 'Hale', 'body', 'Broken arm', true));
chat.push(msg({ stateChanges: [{ name: 'Hale', fields: { body: 'Healed', heart: 'Worried' } }] }));
assert.equal(stateAt().hale.fields.body, 'Broken arm');
assert.equal(stateAt().hale.fields.heart, 'Worried');
assert.equal(stateAt(1).hale.fields.heart, undefined);
assert.match(statePrompt('swipe'), /Broken arm/);
assert.doesNotMatch(statePrompt('swipe'), /Worried/);
assert.match(statePrompt('continue'), /Worried/);
assert(editState(2, 'Hale', 'body', 'Broken arm', false));
chat.push(msg({ stateChanges: [{ name: 'Hale', fields: { body: null } }] }));
assert.equal(stateAt().hale.fields.body, undefined);
chat.pop(); chat.pop();
assert.equal(stateAt().hale.fields.body, 'Broken arm');
assert.deepEqual(changesFromProfiles([{ name: 'Hale', now: { mind: 'Wait', willnot: 'obsolete' } }]), [{ name: 'Hale', fields: { mind: 'Wait' } }]);
assert(saves >= 2);
console.log('state replay, protection, swipe, continue, deletion and prompt: passed');
